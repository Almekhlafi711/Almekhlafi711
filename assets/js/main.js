const languageToggle = document.getElementById("language-toggle");
const themeToggle = document.getElementById("theme-toggle");
const navToggle = document.querySelector(".menu-toggle");
const navLinks = document.querySelector(".nav-links");
const deviceTypeEl = document.getElementById("device-type");
const form = document.getElementById("contact-form");
const formStatus = document.getElementById("form-status");
const backToTop = document.getElementById("back-to-top");
const themeInputs = {
  primary: document.getElementById("primary-color"),
  secondary: document.getElementById("secondary-color"),
  background: document.getElementById("background-color"),
  text: document.getElementById("text-color"),
  font: document.getElementById("font-family")
};

const defaultTheme = {
  primary: "#1a73e8",
  secondary: "#00b894",
  background: "#f7f9fc",
  text: "#1b1f24",
  font: "'Inter', 'Segoe UI', sans-serif",
  mode: "light"
};

const typingTarget = document.querySelector(".typing span");
const typingText = { en: translations.en.hero.title, ar: translations.ar.hero.title };
let typingIndex = 0;
let typingDirection = 1;
let typingLang = "en";

const applyTranslations = (lang) => {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  typingLang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const keys = el.dataset.i18n.split(".");
    const text = keys.reduce((acc, key) => acc?.[key], translations[lang]);
    if (text) {
      el.textContent = text;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const keys = el.dataset.i18nPlaceholder.split(".");
    const text = keys.reduce((acc, key) => acc?.[key], translations[lang]);
    if (text) {
      el.setAttribute("placeholder", text);
    }
  });
};

const applyTheme = (theme) => {
  const root = document.documentElement;
  root.style.setProperty("--primary", theme.primary);
  root.style.setProperty("--secondary", theme.secondary);
  root.style.setProperty("--background", theme.background);
  root.style.setProperty("--text", theme.text);
  root.style.setProperty("--font-family", theme.font);
  root.dataset.theme = theme.mode;
  themeInputs.primary.value = theme.primary;
  themeInputs.secondary.value = theme.secondary;
  themeInputs.background.value = theme.background;
  themeInputs.text.value = theme.text;
  themeInputs.font.value = theme.font;
};

const loadSettings = () => {
  const savedLang = localStorage.getItem("lang") || "en";
  const savedTheme = JSON.parse(localStorage.getItem("theme")) || defaultTheme;
  applyTranslations(savedLang);
  applyTheme(savedTheme);
  languageToggle.setAttribute("aria-pressed", savedLang === "ar");
  themeToggle.setAttribute("aria-pressed", savedTheme.mode === "dark");
};

const saveTheme = () => {
  const theme = {
    primary: themeInputs.primary.value,
    secondary: themeInputs.secondary.value,
    background: themeInputs.background.value,
    text: themeInputs.text.value,
    font: themeInputs.font.value,
    mode: document.documentElement.dataset.theme || "light"
  };
  localStorage.setItem("theme", JSON.stringify(theme));
};

const updateDeviceType = () => {
  const width = window.innerWidth;
  let type = "Desktop";
  if (width < 600) type = "Mobile";
  else if (width < 992) type = "Tablet";
  deviceTypeEl.textContent = type;
};

const initTyping = () => {
  const text = typingText[typingLang];
  if (!typingTarget) return;
  typingTarget.textContent = text.slice(0, typingIndex);
  if (typingIndex === text.length) typingDirection = -1;
  if (typingIndex === 0) typingDirection = 1;
  typingIndex += typingDirection;
  setTimeout(initTyping, 120);
};

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
      }
    });
  },
  { threshold: 0.2 }
);

const skillObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.querySelectorAll(".skill").forEach((skill) => {
          const value = skill.dataset.skill;
          const bar = skill.querySelector(".progress span");
          bar.style.width = `${value}%`;
        });
      }
    });
  },
  { threshold: 0.3 }
);

const initFiltering = () => {
  const buttons = document.querySelectorAll(".filter-btn");
  const cards = document.querySelectorAll(".project-card");
  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      const filter = button.dataset.filter;
      buttons.forEach((btn) => {
        btn.classList.remove("active");
        btn.setAttribute("aria-selected", "false");
      });
      button.classList.add("active");
      button.setAttribute("aria-selected", "true");

      cards.forEach((card) => {
        const category = card.dataset.category;
        card.style.display = filter === "all" || category === filter ? "grid" : "none";
      });
    });
  });
};

const initFormValidation = () => {
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const formData = new FormData(form);
    const name = formData.get("name").trim();
    const email = formData.get("email").trim();
    const message = formData.get("message").trim();

    if (!name || !email || !message) {
      formStatus.textContent = document.documentElement.lang === "ar"
        ? "يرجى تعبئة جميع الحقول المطلوبة."
        : "Please fill in all required fields.";
      formStatus.style.color = "#e74c3c";
      return;
    }

    formStatus.textContent = document.documentElement.lang === "ar"
      ? "تم إرسال رسالتك بنجاح!"
      : "Your message has been sent successfully!";
    formStatus.style.color = "var(--secondary)";
    form.reset();
  });
};

languageToggle.addEventListener("click", () => {
  const newLang = document.documentElement.lang === "en" ? "ar" : "en";
  localStorage.setItem("lang", newLang);
  applyTranslations(newLang);
});

themeToggle.addEventListener("click", () => {
  const isDark = document.documentElement.dataset.theme === "dark";
  document.documentElement.dataset.theme = isDark ? "light" : "dark";
  themeToggle.setAttribute("aria-pressed", !isDark);
  saveTheme();
});

Object.values(themeInputs).forEach((input) => {
  input.addEventListener("input", () => {
    const theme = {
      primary: themeInputs.primary.value,
      secondary: themeInputs.secondary.value,
      background: themeInputs.background.value,
      text: themeInputs.text.value,
      font: themeInputs.font.value,
      mode: document.documentElement.dataset.theme || "light"
    };
    applyTheme(theme);
    saveTheme();
  });
});

navToggle.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");
  navToggle.setAttribute("aria-expanded", isOpen);
});

backToTop.addEventListener("click", () => {
  window.scrollTo({ top: 0, behavior: "smooth" });
});

window.addEventListener("resize", updateDeviceType);

loadSettings();
updateDeviceType();
initTyping();
initFiltering();
initFormValidation();

document.querySelectorAll(".reveal").forEach((el) => revealObserver.observe(el));
document.querySelectorAll(".skill-group").forEach((el) => skillObserver.observe(el));
